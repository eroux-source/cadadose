#!/usr/bin/env bash
# Regenerates src/lib/article-images.ts from the files in public/img/a (run after adding photos).
cd "$(dirname "$0")/.."
{
  echo "/** Generated by scripts/gen-article-images.sh — keys of the per-article photos in public/img/a. */"
  echo "export const ARTICLE_IMAGES = new Set<string>(["
  ls public/img/a 2>/dev/null | sed -n 's/\.webp$//p' | sort | sed 's/.*/  "&",/'
  echo "]);"
} > src/lib/article-images.ts
echo "$(grep -c '^  "' src/lib/article-images.ts) keys"
